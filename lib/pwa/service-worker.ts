// The web app's service worker, served by app/sw.js/route.ts with the build id in it, so every deployment is a
// new worker that drops the previous build's app shell.
//
//   app shell     precached on install: the page shells' /_next/static assets, the manifest, the icons;
//                 any other /_next/static file is cached the first time it loads (hashed, immutable)
//   data          GET /api/me/brief, /api/me/cards, /api/me/cards/{id}: stale-while-revalidate. A cached response
//                 is answered first, marked `x-pbcp-from-cache` with the time it was fetched (the page shows
//                 "as of <time>"), and the network answer is posted to the page when it arrives
//   pages         /brief, /day/{date}, /card/{id} (documents and Next.js's RSC requests): stale-while-revalidate;
//                 a page never opened on this device answers an offline notice
//   media         /api/me/svg/{hash}, /api/me/img?u=&s=: cache-first by URL (content-addressed or signed)
//   everything else, and every request that is not a GET, goes to the network untouched. Nothing is queued:
//   a decision, acknowledgement, snooze or order made offline is refused by the page, never sent later.

export function serviceWorkerSource(build: string): string {
  return `// Generated by lib/pwa/service-worker.ts for build ${JSON.stringify(build)}.
'use strict';
const BUILD = ${JSON.stringify(build)};
const SHELL = 'pbcp-shell-' + BUILD;
const PAGES = 'pbcp-pages';
const DATA = 'pbcp-data';
const MEDIA = 'pbcp-media';
const SHELL_PAGES = ['/brief', '/orders', '/day/2000-01-01', '/card/_'];
const SHELL_FILES = ['/manifest.webmanifest', '/icon.svg', '/icons/icon-192.png', '/icons/icon-512.png', '/icons/maskable-512.png', '/icons/apple-touch-icon.png'];

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const shell = await caches.open(SHELL);
    const pages = await caches.open(PAGES);
    const assets = new Set(SHELL_FILES);
    for (const path of SHELL_PAGES) {
      const res = await fetch(path, { cache: 'no-store', credentials: 'same-origin' });
      if (!res.ok) continue;
      const html = await res.clone().text();
      for (const m of html.matchAll(/(?:src|href)="(\\/_next\\/static\\/[^"]+)"/g)) assets.add(m[1].replace(/&amp;/g, '&'));
      if (path === '/brief') await pages.put(path, stamp(res));
    }
    await shell.addAll([...assets]);
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) if (key.startsWith('pbcp-shell-') && key !== SHELL) await caches.delete(key);
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  // A write goes straight to the network, now or not at all: never cached, never queued. It is passed through
  // here rather than left to the browser so that a keepalive request from a page being unloaded (the brief's
  // last-visit POST on leaving) is carried by the worker's lifetime instead of being dropped with the page.
  if (req.method !== 'GET') return event.respondWith(fetch(req));
  const path = url.pathname;
  if (path.startsWith('/_next/static/')) return event.respondWith(cacheFirst(SHELL, req));
  if (path.startsWith('/api/me/svg/') || path === '/api/me/img') return event.respondWith(cacheFirst(MEDIA, req));
  if (path === '/api/me/brief' || path === '/api/me/cards' || path.startsWith('/api/me/cards/')) return event.respondWith(swr(DATA, req, event, true));
  if (path === '/brief' || path.startsWith('/day/') || path.startsWith('/card/')) return event.respondWith(swr(PAGES, req, event, false));
});

/** A network response as stored: with the time it was fetched. */
function stamp(res) {
  const headers = new Headers(res.headers);
  headers.set('x-pbcp-fetched-at', new Date().toISOString());
  return new Response(res.body, { status: res.status, statusText: res.statusText, headers });
}

/** A stored response as answered from the cache: marked, so the page can say how old it is. */
function fromCache(hit) {
  const headers = new Headers(hit.headers);
  headers.set('x-pbcp-from-cache', '1');
  return new Response(hit.body, { status: hit.status, statusText: hit.statusText, headers });
}

async function cacheFirst(name, req) {
  const cache = await caches.open(name);
  const hit = await cache.match(req, { ignoreVary: true });
  if (hit) return hit;
  const res = await fetch(req);
  if (res.ok) await cache.put(req, res.clone());
  return res;
}

async function post(clientId, message) {
  const client = clientId ? await self.clients.get(clientId) : null;
  for (const c of client ? [client] : await self.clients.matchAll({ type: 'window' })) c.postMessage(message);
}

async function swr(name, req, event, isData) {
  const cache = await caches.open(name);
  const key = req.url;
  const network = fetch(req).then(async (res) => {
    if (res.ok) await cache.put(key, stamp(res.clone()));
    return res;
  });
  // x-pbcp-network: the page asks for the network's answer (after a refreshed session), the cache only as fallback.
  const hit = req.headers.get('x-pbcp-network') ? null : await cache.match(key, { ignoreVary: true });
  if (hit) {
    event.waitUntil(network.then(async (res) => {
      if (!isData) return;
      if (res.ok) await post(event.clientId, { type: 'pbcp-fresh', url: req.url, body: await res.clone().text() });
      else await post(event.clientId, { type: 'pbcp-stale', url: req.url, status: res.status });
    }, () => undefined));
    return fromCache(hit);
  }
  try {
    return await network;
  } catch {
    const fallback = await cache.match(key, { ignoreVary: true });
    if (fallback) return fromCache(fallback);
    if (isData) return Response.json({ error: 'offline', message: 'no network, and nothing cached for this request' }, { status: 503, headers: { 'x-pbcp-offline': '1' } });
    return new Response(OFFLINE_PAGE, { status: 503, headers: { 'content-type': 'text/html; charset=utf-8', 'content-security-policy': "default-src 'none'; style-src 'unsafe-inline'", 'x-pbcp-offline': '1' } });
  }
}

const OFFLINE_PAGE = '<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Offline</title>' +
  '<body style="font:16px system-ui;margin:2rem;max-width:32rem"><h1>Offline</h1><p>This page has not been opened on this device yet, so there is no copy of it here.</p><p><a href="/brief">The brief</a> works offline once it has been opened.</p></body>';
`;
}
