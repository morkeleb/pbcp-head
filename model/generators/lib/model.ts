// The model's shape, as the generators read it (model/README.md "The model format"). Pure: no file is written here.
// The model carries shapes and invariants, never behaviour; these helpers only resolve names and walk it.

export type TypeName = 'string' | 'integer' | 'number' | 'boolean' | 'literal' | 'enum' | 'ref' | 'array' | 'record' | 'object' | 'unknown';

/** A type expression: a field without its name, an array's element, a record's value. */
export interface Spec {
  type: TypeName;
  /** `array`, `record`: the element or value. */
  of?: Spec;
  /** `ref`: a scalar, enum, type or import by name. */
  ref?: string;
  /** `ref` to a schema import: one of its fields (`HeadFieldsSchema.shape.exec_state`). */
  member?: string;
  /** `enum`: inline values. */
  values?: string[];
  /** `literal`. */
  value?: string | number | boolean;
  /** `object`: its fields, and the type or import it extends. */
  fields?: Field[];
  extends?: string;
  /** A name for an inline object, for generators that need one (a Swift struct); the Zod output inlines it. */
  name?: string;
  optional?: boolean;
  nullable?: boolean;
  min?: number;
  nonnegative?: boolean;
  positive?: boolean;
  pattern?: string;
  /** The description the API document carries (`.describe()`). */
  describe?: string;
  /** Where the rule comes from: an RFC section, a doc. Emitted as a comment; never in the API document. */
  doc?: string;
}

export interface Field extends Spec {
  name: string;
}

/** `{ "spread": "HeadFields" }` in a field list: every field of that import's shape, in its place. */
export interface Spread {
  spread: string;
}

export interface Variant {
  fields: Array<Field | Spread>;
  describe?: string;
  /** On a Command variant: the owner route it is sent to. */
  route?: string;
}

export interface TypeDef {
  name: string;
  /** `api` (the default): a Zod schema in lib/api; `store`: a client-store type only. */
  layer?: 'api' | 'store';
  registry?: 'responses' | 'requests';
  /** The id in the API document; the name when absent. */
  id?: string;
  /** The registered description (a component's description in the API document). */
  description?: string;
  /** A description on the schema itself (`.describe()`), for an unregistered type. */
  describe?: string;
  doc?: string;
  /** False: module-private in the generated file. */
  export?: boolean;
  extends?: string;
  fields?: Array<Field | Spread>;
  union?: Variant[];
  /** Another type or import, registered under this name. */
  is?: string;
  /** The same schema under a second name. */
  alias?: string;
  /** An invariant: at least one of these fields is given. */
  atLeastOne?: { fields: string[]; message: string };
}

export interface Import {
  name: string;
  import: string;
  /** A package, or a path from the repo root without extension. */
  from: string;
  kind: 'schema' | 'const';
  doc?: string;
}

export interface Scalar extends Spec {
  name: string;
}

export interface EnumDef {
  name: string;
  values?: string[];
  /** A constant import holding the values (core's), and values added after them. */
  from?: string;
  plus?: string[];
  /** Exported as a constant array under this name. */
  export?: string;
  layer?: 'api' | 'store';
  doc?: string;
}

export interface ObjectStore {
  const: string;
  name: string;
  keyPath: string;
  autoIncrement?: boolean;
  /** The entity a row is (`Meta`: one row per field, `{ key, value }`). */
  holds: string;
  indexes?: Array<{ name: string; keyPath: string }>;
}

export interface Model {
  imports: Import[];
  scalars: Scalar[];
  enums: EnumDef[];
  types: TypeDef[];
  store: { version: number; doc?: string; objectStores: ObjectStore[] };
}

export const isSpread = (f: Field | Spec | Spread): f is Spread => 'spread' in f;

export const HEADER = (generator: string) =>
  `// GENERATED by Clay from model/model.json (generator ${generator}). Do not edit: change the model and run \`pnpm generate\`.\n` +
  `// model/README.md says what the model holds and how this file is made.\n`;

/** A JS string literal: single-quoted, or a template literal when the text interpolates a model import (`\${NAME}`). */
export function str(s: string): string {
  if (/\$\{[A-Z_]+\}/.test(s)) return `\`${s.replace(/\\/g, '\\\\').replace(/`/g, '\\`')}\``;
  return `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

/** An object key: bare when it is an identifier, else quoted (`'orders.claim_seq'`). */
export const key = (k: string) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : str(k));

export function comment(doc: string | undefined, indent: string): string {
  return doc ? `${indent}/** ${doc.replace(/\*\//g, '*\\/')} */\n` : '';
}

export const layerOf = (t: { layer?: 'api' | 'store' }) => t.layer ?? 'api';

/** The API types a store-layer type or the store reads, by name, transitively through refs and extends. */
export function apiTypesUsedByStore(m: Model, { unions = true }: { unions?: boolean } = {}): string[] {
  const api = new Set(m.types.filter((t) => layerOf(t) === 'api').map((t) => t.name));
  const used = new Set<string>();
  const visit = (s: Spec | Field | Spread | undefined) => {
    if (!s || isSpread(s)) return;
    if (s.ref && api.has(s.ref)) used.add(s.ref);
    if (s.extends && api.has(s.extends)) used.add(s.extends);
    visit(s.of);
    s.fields?.forEach(visit);
  };
  for (const t of m.types.filter((t) => layerOf(t) === 'store' && (unions || !t.union))) {
    if (t.extends && api.has(t.extends)) used.add(t.extends);
    t.fields?.forEach(visit);
    t.union?.forEach((v) => v.fields.forEach(visit));
  }
  for (const s of m.store.objectStores) if (api.has(s.holds)) used.add(s.holds);
  return [...used].sort();
}
